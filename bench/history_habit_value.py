"""Oracle decision value of a planted opponent habit (local CPU, frozen models).

Question: is knowing a planted style z worth changing the current action?
Opponents are the Sept 30 habit pack: u2623 with pi_z(a) ∝ pi(a) exp(z b f(a))
on one axis (train/history_habit.py), z in {-1, +1} with a 50/50 prior. The
observer team plays plain u2623. Prefixes are generated by plain u2623 on all
seats; z is assigned at the node, hidden hands are uniformly redrawn there,
and each candidate is rolled out to the end of the round.

The oracle is told z; no model reads history here. Two estimates bracket the
oracle value: the pooled plug-in (biased up by max selection) and the
cross-fitted realised gain (select on one half of worlds, score on the other;
biased down by selection noise). The interaction estimate multiplies the two
halves' centred type differences and is unbiased for its square.

Run with the checkpoint-matching model root first on PYTHONPATH. Stages:
generate -> run -> analyze, all in one fresh output directory.
"""
from __future__ import annotations

import argparse
from concurrent.futures import ProcessPoolExecutor, as_completed
import hashlib
import json
import multiprocessing as mp
from pathlib import Path
import time
from typing import Any

import gd
import numpy as np
import torch

from bench.history_value_tasks import Listener, candidates_for, decision_probabilities, rollout
from eval.history_policy import apply_and_observe
from train.history_habit import StyledActor
from train.history_model import PublicStream, load_history_checkpoint

BASE = Path('.work/lineage/main/u02623-172M.pt')
SEED = 17101801  # 17101800 was the speed pilot (.work/history-habit-value-pilot)
DEALS = 12
CAP = 6
SPLIT_WORLDS = 256
CHUNK = 64
WORKERS = 10
# (axis, strength). lead_single b=1 is the Sept 30 phase-1a pack; pass b=4 is
# a positive control that should show value if the instrument works.
CONFIGS = (('lead_single', 1.0), ('lead_single', 2.0), ('pass', 1.0), ('pass', 2.0),
           ('pass', 4.0), ('bomb', 1.0), ('bomb', 2.0))


class StyledTable(StyledActor):
    """Styled log-probability table for the rollout path, which samples from
    ``_log_prob_table`` directly. Not for ``act`` (that would tilt twice)."""

    def _log_prob_table(self, inputs, encoded, max_candidates, inference_log_probs=None):
        base = (self.candidate_log_probs(inputs, encoded=encoded)
                if inference_log_probs is None else inference_log_probs)
        styled = self.styled_log_probs(inputs, base).float()
        return super()._log_prob_table(inputs, encoded, max_candidates, styled)


def sha(path: str | Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def load_plain(path: Path) -> Any:
    actor, _, _ = load_history_checkpoint(path, 'cpu')
    return actor.eval().requires_grad_(False)


def load_styled(path: Path, axis: str, strength: float) -> dict[int, StyledTable]:
    """Type 0 is z = -1, type 1 is z = +1; one frozen copy each."""
    base, _, _ = load_history_checkpoint(path, 'cpu')
    out = {}
    for t, z in enumerate((-1, 1)):
        m = StyledTable(base.config)
        m.load_state_dict(base.state_dict())
        out[t] = m.set_style(axis, strength, z).eval().requires_grad_(False)
    return out


def world_seeds(node: int, split: int) -> np.ndarray:
    ss = np.random.SeedSequence([SEED, 1, node, split])
    return np.random.default_rng(ss).integers(1, 2**63 - 1, size=SPLIT_WORLDS)


def generate(actor: Any, output: Path) -> list[dict]:
    """Two seat-0 nodes per deal: one early/mid (60-100 cards left), one late (<= 56)."""
    engine = gd.Engine()
    engine.auto_pass = False
    deals = np.random.default_rng(SEED).integers(1, 2**63 - 1, size=DEALS)
    nodes = []
    for d, deal in enumerate(deals):
        state = gd.MatchState()
        engine.new_match(state, int(deal))
        stream = PublicStream()
        listener = Listener(stream)
        want = {'early': lambda t: 60 <= t <= 100, 'late': lambda t: t <= 56}
        for step in range(512):
            if state.phase == gd.Phase.RoundEnd or not want:
                break
            legal = engine.legal_actions(state)
            hands = [len(state.hand(s)) for s in range(4)]
            arrays = tuple(x.copy() for x in stream.arrays())
            p = decision_probabilities(actor, state, arrays)
            if state.to_move == 0 and len(legal) >= 3 and min(hands) > 0:
                for name, ok in list(want.items()):
                    if ok(sum(hands)):
                        cand = candidates_for(legal, p, p[None], CAP)
                        folder = output / 'nodes' / f'node-{len(nodes):02d}'
                        folder.mkdir(parents=True)
                        (folder / 'simulator-state.bin').write_bytes(state.serialize())
                        np.savez_compressed(folder / 'public-inputs.npz', tokens=arrays[0],
                                            rounds=arrays[1], phases=arrays[2], candidates=cand,
                                            actor_prob=p)
                        nodes.append(dict(node=len(nodes), deal=d, deal_seed=int(deal), step=step,
                                          stage=name, hands=hands, legal=len(legal),
                                          candidates=cand.tolist(),
                                          kinds=[str(legal[a].type) for a in cand]))
                        del want[name]
                        break
            apply_and_observe(engine, state, legal[int(np.argmax(p))], [listener])
        else:
            raise RuntimeError('generation step cap hit')
    return nodes


_MODELS: dict = {}


def init_worker(base: str) -> None:
    torch.set_num_threads(1)
    _MODELS['self'] = load_plain(Path(base))
    for axis, b in CONFIGS:
        _MODELS[(axis, b)] = load_styled(Path(base), axis, b)


def work(output: str, config: int, node: int, split: int, chunk: int) -> str:
    out = Path(output) / 'q' / f'c{config}-n{node:02d}-s{split}-k{chunk}.npy'
    if out.exists():
        return str(out)
    state = gd.MatchState.deserialize((Path(output) / 'nodes' / f'node-{node:02d}' / 'simulator-state.bin').read_bytes())
    with np.load(Path(output) / 'nodes' / f'node-{node:02d}' / 'public-inputs.npz') as raw:
        arrays = tuple(raw[k].copy() for k in ('tokens', 'rounds', 'phases'))
        cand = raw['candidates'].copy()
    seeds = world_seeds(node, split)[chunk * CHUNK:(chunk + 1) * CHUNK]
    values = rollout(_MODELS['self'], _MODELS[CONFIGS[config]], state, arrays, cand, seeds)
    tmp = out.with_suffix('.tmp.npy')
    np.save(tmp, values)
    tmp.rename(out)
    return str(out)


def load_q(output: Path, config: int, node: int, split: int) -> np.ndarray:
    """[type, candidate, world, (win, return)]."""
    parts = [np.load(output / 'q' / f'c{config}-n{node:02d}-s{split}-k{k}.npy')
             for k in range(SPLIT_WORLDS // CHUNK)]
    return np.concatenate(parts, axis=2)


def node_metrics(qa: np.ndarray, qb: np.ndarray) -> dict:
    """Per-node oracle-value estimates from two independent world halves (one metric)."""
    ma, mb = qa.mean(2), qb.mean(2)          # [type, candidate]
    pooled = (ma + mb) / 2

    def realised(sel: np.ndarray, test: np.ndarray) -> float:
        prior = int(np.argmax(sel.mean(0)))
        ident = sel.argmax(1)
        return float(np.mean([test[t, ident[t]] for t in range(len(test))]) - test[:, prior].mean())

    da, db = ma[1] - ma[0], mb[1] - mb[0]
    da, db = da - da.mean(), db - db.mean()
    return dict(
        plugin=float(pooled.max(1).mean() - pooled.mean(0).max()),
        crossfit=(realised(ma, mb) + realised(mb, ma)) / 2,
        interaction_sq=float(np.mean(da * db)),
        type_effect=float((pooled[1] - pooled[0]).mean()),
        top_differs=bool(pooled[0].argmax() != pooled[1].argmax()),
        mean_win=pooled.mean(1).tolist())


def node_bootstrap(x: np.ndarray, n: int = 10000, seed: int = 0) -> list[float]:
    idx = np.random.default_rng(seed).integers(0, len(x), size=(n, len(x)))
    return np.percentile(x[idx].mean(1), [2.5, 97.5]).tolist()


def analyze(output: Path, nodes: list[dict]) -> dict:
    rows = []
    for c, (axis, b) in enumerate(CONFIGS):
        per = {m: [] for m in ('win', 'return')}
        for n in range(len(nodes)):
            qa, qb = load_q(output, c, n, 0), load_q(output, c, n, 1)
            for i, m in enumerate(('win', 'return')):
                per[m].append(node_metrics(qa[..., i], qb[..., i]))
        row = dict(axis=axis, strength=b)
        for m, scale in (('win', 100.0), ('return', 1.0)):
            r = per[m]
            plugin = np.array([x['plugin'] for x in r]) * scale
            cross = np.array([x['crossfit'] for x in r]) * scale
            inter = np.array([x['interaction_sq'] for x in r]) * scale**2
            eff = np.array([x['type_effect'] for x in r]) * scale
            row[m] = dict(
                plugin=float(plugin.mean()), plugin_ci=node_bootstrap(plugin, seed=1),
                crossfit=float(cross.mean()), crossfit_ci=node_bootstrap(cross, seed=2),
                interaction_rms=float(np.sqrt(max(inter.mean(), 0.0))),
                interaction_sq=float(inter.mean()), interaction_sq_ci=node_bootstrap(inter, seed=3),
                type_effect=float(eff.mean()), type_effect_ci=node_bootstrap(eff, seed=4),
                top_differs=int(sum(x['top_differs'] for x in r)),
                per_node_crossfit=cross.tolist(), per_node_plugin=plugin.tolist())
        rows.append(row)
    return dict(units=dict(win='percentage points of round team win', ret='PPO seat_return'),
                nodes=len(nodes), configs=rows)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--stage', choices=('generate', 'run', 'analyze'), required=True)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--workers', type=int, default=WORKERS)
    p.add_argument('--configs', type=str, default='',
                   help='comma-separated config indices for a pilot (default all)')
    p.add_argument('--nodes', type=int, default=0, help='first N nodes only (pilot)')
    p.add_argument('--chunks', type=int, default=0, help='first K chunks per split (pilot)')
    args = p.parse_args()
    torch.set_num_threads(1)
    if args.stage == 'generate':
        args.output.mkdir(parents=True, exist_ok=False)
        import train.history_model as model
        nodes = generate(load_plain(BASE), args.output)
        branches = len(CONFIGS) * sum(2 * len(n['candidates']) * 2 * SPLIT_WORLDS for n in nodes)
        protocol = dict(
            base=str(BASE), base_sha=sha(BASE), source_sha=sha(__file__),
            model_source_sha=sha(model.__file__), engine_sha=sha(gd._gd_core.__file__),
            seed=SEED, deals=DEALS, nodes=len(nodes), candidate_cap=CAP,
            split_worlds=SPLIT_WORLDS, configs=[list(c) for c in CONFIGS], branches=branches,
            primary='round team win (pp); secondary PPO seat_return',
            estimates='pooled plug-in (upper-biased), cross-fitted realised gain (lower-biased), '
                      'unbiased squared type x action interaction; node bootstrap 95% CI',
            boundary='Oracle z given to the planner only; no history reading; one-step change at '
                     'the node, fixed sampled continuation; uniform hand redraw at the node; '
                     'no training, no budget extension')
        (args.output / 'protocol.json').write_text(json.dumps(protocol, indent=2) + '\n')
        (args.output / 'nodes.json').write_text(json.dumps(nodes, indent=2) + '\n')
        print(f'{len(nodes)} nodes, {branches} branches fixed')
        return
    protocol = json.loads((args.output / 'protocol.json').read_text())
    if protocol['source_sha'] != sha(__file__) or protocol['base_sha'] != sha(BASE):
        raise ValueError('source or checkpoint changed since generate')
    nodes = json.loads((args.output / 'nodes.json').read_text())
    if args.stage == 'run':
        (args.output / 'q').mkdir(exist_ok=True)
        configs = [int(c) for c in args.configs.split(',')] if args.configs else range(len(CONFIGS))
        count = args.nodes or len(nodes)
        chunks = args.chunks or SPLIT_WORLDS // CHUNK
        jobs = [(c, n, s, k) for c in configs for n in range(count) for s in (0, 1) for k in range(chunks)]
        start = time.time()
        ctx = mp.get_context('spawn')
        with ProcessPoolExecutor(args.workers, mp_context=ctx, initializer=init_worker,
                                 initargs=(str(BASE),)) as pool:
            futures = [pool.submit(work, str(args.output), *j) for j in jobs]
            for i, f in enumerate(as_completed(futures), 1):
                f.result()
                if i % 20 == 0 or i == len(jobs):
                    print(f'{i}/{len(jobs)} jobs, {time.time() - start:.0f}s', flush=True)
        return
    summary = analyze(args.output, nodes)
    (args.output / 'summary.json').write_text(json.dumps(summary, indent=2) + '\n')
    for r in summary['configs']:
        w = r['win']
        print(f"{r['axis']:>11} b={r['strength']:.0f}  plug-in {w['plugin']:+.2f} "
              f"[{w['plugin_ci'][0]:+.2f},{w['plugin_ci'][1]:+.2f}]  cross-fit {w['crossfit']:+.2f} "
              f"[{w['crossfit_ci'][0]:+.2f},{w['crossfit_ci'][1]:+.2f}]  interaction rms {w['interaction_rms']:.2f}  "
              f"type effect {w['type_effect']:+.2f}  top differs {w['top_differs']}/{summary['nodes']}")


if __name__ == '__main__':
    main()
